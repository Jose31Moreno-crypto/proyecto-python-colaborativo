def agregar_suenos(nombre):
    # Mi aporte: sueños y motivaciones del protagonista
    print("\n--- LOS SUEÑOS DEL PROTAGONISTA ---")

    inspiracion = input("¿Quién te inspira a seguir adelante?: ")
    habilidad = input("¿Qué habilidad te gustaría aprender?: ")
    futuro = input("¿Cómo imaginas tu vida dentro de cinco años?: ")

    print("\n--- EL FUTURO DE MI HISTORIA ---")
    print(f"En su camino hacia el éxito, {nombre} encuentra inspiración en {inspiracion}.")
    print(f"Uno de sus nuevos desafíos es aprender {habilidad}.")
    print(f"Cuando piensa en los próximos cinco años, {nombre} se imagina {futuro}.")
    print(f"Con esfuerzo y dedicación, {nombre} continúa construyendo su futuro.")
    print("Cada día representa una nueva oportunidad para alcanzar sus sueños.")
